        // --- Tick -------------------------------------------------------------------------

        // fighting: a standing preman is close to the hero. heroDown: the hero lies in Runtuh.
        public void Tick(KarierPoint hero, float deltaTime, bool fighting, bool heroDown)
        {
            if (deltaTime <= 0f)
                return;
            if (EatLeft > 0f)
                EatLeft = Math.Max(0f, EatLeft - deltaTime);
            if (JailLeft > 0f)
            {
                JailLeft -= deltaTime;
                if (JailLeft <= 0f)
                {
                    JailLeft = 0f;
                    Say("Masa tahanan selesai. Pintu sel dibuka: \"Jangan diulangi, ya!\"");
                    Cue(KarierCue.Notif);
                }
            }
            if (BuzzerCooldown > 0f)
                BuzzerCooldown = Math.Max(0f, BuzzerCooldown - deltaTime);

            if (RebahanLeft > 0f)
            {
                RebahanLeft -= deltaTime;
                if (RebahanLeft <= 0f)
                {
                    RebahanLeft = 0f;
                    AddEnergi(CampaignTuning.Karier.RebahanEnergi);
                    Say("Bangun dari rebahan. ENERGI +" + CampaignTuning.Karier.RebahanEnergi +
                        ". Dua jam hilang, dompet tetap tipis.");
                    Cue(KarierCue.Notif);
                }
            }

            if (!heroDown && !InJail)
                TickJob(hero, deltaTime);
            TickKeributan(deltaTime, fighting && !heroDown);
            CheckMission();
        }

        private void TickJob(KarierPoint hero, float deltaTime)
        {
            float radius = CampaignTuning.Karier.ZoneRadius;
            switch (Step)
            {
                case KarierStep.OjolJemput:
                    if (Fill(KarierPoint.Near(hero, Place(OjolFrom), radius), deltaTime, CampaignTuning.Karier.OjolPickupSeconds))
                    {
                        Step = KarierStep.OjolAntar;
                        float distance = KarierPoint.Distance(Place(OjolFrom), Place(OjolTo));
                        OjolTimeLimit = distance * CampaignTuning.Karier.OjolSecondsPerMeter + CampaignTuning.Karier.OjolGraceSeconds;
                        OjolTimeLeft = OjolTimeLimit;
                        Say("Penumpang naik. Antar ke " + PlaceName(OjolTo) + " dalam " + (int)Math.Ceiling(OjolTimeLimit) + " detik!");
                        Cue(KarierCue.Notif);
                    }
                    break;
                case KarierStep.OjolAntar:
                    OjolTimeLeft -= deltaTime;
                    if (Fill(KarierPoint.Near(hero, Place(OjolTo), radius), deltaTime, CampaignTuning.Karier.OjolPickupSeconds))
                        CompleteOjol();
                    break;
                case KarierStep.KuliAmbil:
                    if (Fill(KarierPoint.Near(hero, layout.KuliPickup, radius), deltaTime, CampaignTuning.Karier.KuliPickSeconds))
                    {
                        Carrying = true;
                        Step = KarierStep.KuliAntar;
                        Say("Sak semen " + (KuliDelivered + 1) + "/" + CampaignTuning.Karier.KuliSacks + " di pundak. Bawa ke PROYEK.");
                    }
                    break;
                case KarierStep.KuliAntar:
                    if (Fill(KarierPoint.Near(hero, layout.KuliDrop, radius), deltaTime, CampaignTuning.Karier.KuliDropSeconds))
                    {
                        Carrying = false;
                        KuliDelivered++;
                        AddEnergi(-CampaignTuning.Karier.KuliEnergiPerSack);
                        if (KuliDelivered >= CampaignTuning.Karier.KuliSacks)
                            CompleteKuli();
                        else
                        {
                            Step = KarierStep.KuliAmbil;
                            Say("Sak " + KuliDelivered + "/" + CampaignTuning.Karier.KuliSacks + " beres. Ambil lagi di TUMPUKAN SEMEN.");
                            if (Energi <= 0)
                            {
                                Say("Badan remuk, ENERGI habis. Kerja kuli berhenti tanpa upah. REBAHAN atau MAKAN dulu.");
                                Cue(KarierCue.Gagal);
                                EndJob();
                            }
                        }
                    }
                    break;
                case KarierStep.BuzzerKetik:
                    if (Fill(KarierPoint.Near(hero, layout.Warkop, radius), deltaTime, CampaignTuning.Karier.BuzzerTypeSeconds))
                        CompleteBuzzer();
                    break;
            }
        }

        // Standing in the zone fills the step; leaving resets it. True once full.
        private bool Fill(bool inside, float deltaTime, float seconds)
        {
            if (!inside)
            {
                StepProgress = 0f;
                return false;
            }
            StepProgress += deltaTime / Math.Max(0.05f, seconds);
            if (StepProgress < 1f)
                return false;
            StepProgress = 0f;
            return true;
        }

        private void TickKeributan(float deltaTime, bool fighting)
        {
            if (PoliceCalled)
                return;
            // 0.6.1: once warga shouted, someone always calls the police; they come late,
            // even when the fight is already over (owner: the police must not skip a fight).
            if (Shouted && PoliceEta < 0f)
                PoliceEta = CampaignTuning.Karier.PolisiDatangSeconds;
            if (PoliceEta > 0f)
            {
                PoliceEta -= deltaTime;
                if (PoliceEta <= 0f)
                {
                    CallPolice(KarierPoliceReason.Keributan);
                    return;
                }
            }
            if (CalmLeft > 0f)
            {
                CalmLeft = Math.Max(0f, CalmLeft - deltaTime);
                return;
            }
            if (fighting)
            {
                Keributan = Math.Min(1f, Keributan + deltaTime / CampaignTuning.Karier.KeributanFillSeconds);
                energiCarry += CampaignTuning.Karier.FightEnergiPerSecond * deltaTime;
                if (energiCarry >= 1f)
                {
                    int lost = (int)energiCarry;
                    energiCarry -= lost;
                    AddEnergi(-lost);
                }
                if (!Shouted && Keributan >= CampaignTuning.Karier.TeriakAt)
                {
                    Shouted = true;
                    Say("Warga teriak: \"WOI! ADA YANG BERANTEM!\"  Tetangga berdatangan, HP merekam, ada yang telepon polisi.");
                    Cue(KarierCue.Teriak);
                }
                if (!MeleraiDone && Keributan >= CampaignTuning.Karier.MeleraiAt)
                {
                    MeleraiDone = true;
                    CalmLeft = CampaignTuning.Karier.MeleraiSeconds;
                    Say("Pak RT melerai: \"Sudah, sudah! Malu sama tetangga!\"  Kalau masih ribut, polisi dipanggil.");
                    Cue(KarierCue.Melerai);
                }
                if (Keributan >= 1f)
                    CallPolice(KarierPoliceReason.Keributan);
            }
            else if (Keributan > 0f)
            {
                Keributan = Math.Max(0f, Keributan - deltaTime / CampaignTuning.Karier.KeributanDecaySeconds);
                if (Keributan <= 0f && PoliceEta < 0f)
                    Shouted = MeleraiDone = false;
            }
        }

        // --- Jobs -------------------------------------------------------------------------

        public bool TakeJob(KarierJob job, out string reason)
        {
            reason = null;
            if (job == KarierJob.None)
                reason = "Pilih pekerjaan dulu.";
            else if (Busy)
                reason = "Selesaikan atau batalkan kerja yang sekarang dulu.";
            else if (Rebahan)
                reason = "Masih rebahan.";
            else if (PoliceCalled)
                reason = "Urusan dengan polisi belum selesai.";
            else if (InJail)
                reason = "Masih di dalam sel.";
            else if (job == KarierJob.Ojol && Energi < CampaignTuning.Karier.OjolEnergi)
                reason = "ENERGI habis. REBAHAN atau MAKAN dulu.";
            else if (job == KarierJob.Kuli && Energi < CampaignTuning.Karier.KuliEnergiPerSack * 2)
                reason = "Terlalu lemas untuk angkat semen. REBAHAN atau MAKAN dulu.";
            else if (job == KarierJob.Buzzer && BuzzerCooldown > 0f)
                reason = "Juragan buzzer belum kirim order. Tunggu " + (int)Math.Ceiling(BuzzerCooldown) + " detik.";
            else if (job == KarierJob.Ojol && !NewOjolOrder())
                reason = "Belum ada order di sekitar.";
            if (reason != null)
                return false;

            if (Ride != KarierRide.None)
            {
                Say((Ride == KarierRide.Motor ? "Motor sewaan" : "Sepeda sewaan") + " dikembalikan dulu.");
                Ride = KarierRide.None;
            }
            Job = job;
            StepProgress = 0f;
            switch (job)
            {
                case KarierJob.Ojol:
                    Step = KarierStep.OjolJemput;
                    Say("ORDER MASUK: jemput penumpang di " + PlaceName(OjolFrom) + ", antar ke " + PlaceName(OjolTo) + ".");
                    break;
                case KarierJob.Kuli:
                    Step = KarierStep.KuliAmbil;
                    KuliDelivered = 0;
                    Say("Mandor: \"Angkut " + CampaignTuning.Karier.KuliSacks + " sak semen dari TUMPUKAN ke PROYEK. Upah dibayar kalau beres.\"");
                    break;
                case KarierJob.Buzzer:
                    Step = KarierStep.BuzzerKetik;
                    Say("Juragan buzzer: \"Duduk di WARKOP, sebar pesan ini ke semua grup WA. Jangan tanya sumbernya.\"");
                    break;
            }
            Cue(KarierCue.Notif);
            return true;
        }

        public void CancelJob()
        {
            if (!Busy)
                return;
            Say(Job == KarierJob.Kuli ? "Kerja kuli ditinggal. Mandor: \"Upah hangus, ya!\"" : "Kerja dibatalkan.");
            EndJob();
        }

        private void EndJob()
        {
            Job = KarierJob.None;
            Step = KarierStep.None;
            StepProgress = 0f;
            Carrying = false;
            KuliDelivered = 0;
            OjolFrom = OjolTo = -1;
        }

        private bool NewOjolOrder()
        {
            int count = layout.Places.Length;
            if (count < 2)
                return false;
            for (int attempt = 0; attempt < 24; attempt++)
            {
                int from = random.Next(count);
                int to = random.Next(count);
                if (from == to || KarierPoint.Distance(layout.Places[from], layout.Places[to]) < CampaignTuning.Karier.OjolMinTrip)
                    continue;
                OjolFrom = from;
                OjolTo = to;
                return true;
            }
            OjolFrom = 0;
            OjolTo = count - 1;
            return true;
        }

        public static int OjolGrossFare(float meters) =>
            Round500(CampaignTuning.Karier.OjolBaseFare + CampaignTuning.Karier.OjolFarePerMeter * Math.Max(0f, meters));

        private void CompleteOjol()
        {
            float distance = KarierPoint.Distance(Place(OjolFrom), Place(OjolTo));
            int gross = OjolGrossFare(distance);
            int cut = Round500(gross * CampaignTuning.Karier.OjolAppCut);
            int net = gross - cut;
            bool late = OjolTimeLeft < 0f;
            if (late)
                net = Round500(net * 0.5f);
            AddDuit(net);
            AddEnergi(-CampaignTuning.Karier.OjolEnergi);
            TripsOjol++;
            if (!late)
                AddRestu(CampaignTuning.Karier.OjolRestuOnTime);
            Say((late ? "TELAT! Penumpang kasih bintang 1, tarif dipotong separuh. " : "Sampai tepat waktu, bintang 5! ") +
                "Tarif " + Rupiah(gross) + " - potongan aplikasi " + Rupiah(cut) + (late ? " - denda telat" : string.Empty) +
                " = " + Rupiah(net) + ".");
            Cue(KarierCue.Koin);

            StepProgress = 0f;
            if (Energi < CampaignTuning.Karier.OjolEnergi)
            {
                Say("Lemas. Aplikasi ojol dimatikan dulu. REBAHAN atau MAKAN.");
                EndJob();
                return;
            }
            NewOjolOrder();
            Step = KarierStep.OjolJemput;
            Say("Order baru: jemput di " + PlaceName(OjolFrom) + " (buka HP untuk berhenti narik).");
        }

        private void CompleteKuli()
        {
            int net = CampaignTuning.Karier.KuliWage - CampaignTuning.Karier.KuliMandorCut;
            AddDuit(net);
            AddRestu(CampaignTuning.Karier.KuliRestu);
            SetKuli++;
            Say("UPAH KULI " + Rupiah(CampaignTuning.Karier.KuliWage) + " - uang rokok mandor " +
                Rupiah(CampaignTuning.Karier.KuliMandorCut) + " = " + Rupiah(net) + ". Kerja keras, hasil pas-pasan.");
            Cue(KarierCue.Koin);
            EndJob();
        }

