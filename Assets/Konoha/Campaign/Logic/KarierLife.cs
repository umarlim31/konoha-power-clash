        private bool NewOjolOrder()
        {
            int count = layout.Places.Length;
            if (count < 2)
                return false;
            for (int attempt = 0; attempt < 24; attempt++)
            {
                int from = random.Next(count);
                int to = random.Next(count);
                if (from == to || KarierPoint.Distance(layout.Places[from], layout.Places[to]) < CampaignTuning.Karier.OjolMinTrip)
                    continue;
                OjolFrom = from;
                OjolTo = to;
                return true;
            }
            OjolFrom = 0;
            OjolTo = count - 1;
            return true;
        }

        public static int OjolGrossFare(float meters) =>
            Round500(CampaignTuning.Karier.OjolBaseFare + CampaignTuning.Karier.OjolFarePerMeter * Math.Max(0f, meters));

        private void CompleteOjol()
        {
            float distance = KarierPoint.Distance(Place(OjolFrom), Place(OjolTo));
            int gross = OjolGrossFare(distance);
            bool night = Night;
            if (night)
                gross = Round500(gross * (1f + CampaignTuning.Karier.OjolNightBonus));
            int cut = Round500(gross * CampaignTuning.Karier.OjolAppCut);
            int net = gross - cut;
            bool late = OjolTimeLeft < 0f;
            if (late)
                net = Round500(net * 0.5f);
            AddDuit(net);
            AddEnergi(-CampaignTuning.Karier.OjolEnergi);
            TripsOjol++;
            if (!late)
                AddRestu(CampaignTuning.Karier.OjolRestuOnTime);
            Say((late ? "TELAT! Penumpang kasih bintang 1, tarif dipotong separuh. " : "Sampai tepat waktu, bintang 5! ") +
                (night ? "Tarif malam " : "Tarif ") + Rupiah(gross) + " - potongan aplikasi " + Rupiah(cut) + (late ? " - denda telat" : string.Empty) +
                " = " + Rupiah(net) + ".");
            Cue(KarierCue.Koin);

            StepProgress = 0f;
            if (Energi < CampaignTuning.Karier.OjolEnergi)
            {
                Say("Lemas. Aplikasi ojol dimatikan dulu. REBAHAN atau MAKAN.");
                EndJob();
                return;
            }
            NewOjolOrder();
            Step = KarierStep.OjolJemput;
            Say("Order baru: jemput di " + PlaceName(OjolFrom) + " (buka HP untuk berhenti narik).");
        }

