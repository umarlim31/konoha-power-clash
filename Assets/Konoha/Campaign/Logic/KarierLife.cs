            if (index < 0 || index >= TugasCount)
                return 0;
            if (TugasDay != Day)
                return 0;
            int done = TugasCounter(TugasKind(index)) - tugasBase[index];
            return Math.Max(0, Math.Min(TugasNeed(index), done));
        }

        public bool TugasDone(int index) => (TugasMask & (1 << index)) != 0;

