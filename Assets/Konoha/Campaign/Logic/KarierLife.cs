    // The player's own citizen (character creator). Indices pick from the name lists.
    public struct KarierAvatar
    {
        public static readonly string[] SkinNames = { "LANGSAT", "SAWO MATANG", "SAWO GELAP", "KUNING LANGSAT" };
        public static readonly string[] HairNames = { "RAMBUT PENDEK", "RAMBUT PANJANG", "PECI", "JILBAB", "TOPI" };
        public static readonly string[] BodyNames = { "KURUS", "SEDANG", "BERISI" };
        public static readonly string[] ShirtNames = { "PUTIH", "HITAM", "MERAH", "BIRU", "HIJAU", "KUNING", "ABU-ABU" };
        public const int MaxNameLength = 14;

        public string Name;
        public bool Female;
        public int Skin, Hair, Body, Shirt;

        public static KarierAvatar Default => new KarierAvatar { Name = "WARGA", Female = false, Skin = 1, Hair = 0, Body = 1, Shirt = 0 };

        public KarierAvatar Clamped()
        {
            KarierAvatar result = this;
            result.Name = CleanName(Name);
            result.Skin = Wrap(Skin, SkinNames.Length);
            result.Hair = Wrap(Hair, HairNames.Length);
            result.Body = Wrap(Body, BodyNames.Length);
            result.Shirt = Wrap(Shirt, ShirtNames.Length);
            return result;
        }

        public static int Wrap(int value, int count) => count <= 0 ? 0 : ((value % count) + count) % count;

        // Upper case letters, digits and spaces, at most 14 characters; never empty.
        public static string CleanName(string raw)
        {
            if (string.IsNullOrEmpty(raw))
                return "WARGA";
            var builder = new StringBuilder(MaxNameLength);
            foreach (char c in raw.ToUpperInvariant())
            {
                if (builder.Length >= MaxNameLength)
                    break;
                if ((c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || (c == ' ' && builder.Length > 0))
                    builder.Append(c);
            }
            string name = builder.ToString().Trim();
            return name.Length == 0 ? "WARGA" : name;
        }

        public string Serialize()
        {
            KarierAvatar a = Clamped();
            return "A1;" + a.Name + ";" + (a.Female ? 1 : 0) + ";" + a.Skin + ";" + a.Hair + ";" + a.Body + ";" + a.Shirt;
        }

        public static bool TryParse(string text, out KarierAvatar avatar)
        {
            avatar = Default;
            if (string.IsNullOrEmpty(text))
                return false;
            string[] parts = text.Split(';');
            if (parts.Length != 7 || parts[0] != "A1")
                return false;
            if (!Int(parts[2], out int female) || !Int(parts[3], out int skin) || !Int(parts[4], out int hair) ||
                !Int(parts[5], out int body) || !Int(parts[6], out int shirt))
                return false;
            avatar = new KarierAvatar { Name = parts[1], Female = female == 1, Skin = skin, Hair = hair, Body = body, Shirt = shirt }.Clamped();
            return true;
        }

        internal static bool Int(string text, out int value) =>
            int.TryParse(text, NumberStyles.Integer, CultureInfo.InvariantCulture, out value);
    }

