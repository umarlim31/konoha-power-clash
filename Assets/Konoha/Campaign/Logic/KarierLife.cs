    // Ground position (x, z) without UnityEngine.
    public struct KarierPoint
    {
        public readonly float X, Z;

        public KarierPoint(float x, float z)
        {
            X = x;
            Z = z;
        }

        public static float Distance(KarierPoint a, KarierPoint b)
        {
            float dx = a.X - b.X, dz = a.Z - b.Z;
            return (float)Math.Sqrt(dx * dx + dz * dz);
        }

        public static bool Near(KarierPoint a, KarierPoint b, float radius) => Distance(a, b) <= radius;
    }

