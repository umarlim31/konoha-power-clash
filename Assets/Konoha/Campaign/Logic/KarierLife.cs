        // Standing in the zone fills the step; leaving resets it. True once full.
        private bool Fill(bool inside, float deltaTime, float seconds)
        {
            if (!inside)
            {
                StepProgress = 0f;
                return false;
            }
            StepProgress += deltaTime / Math.Max(0.05f, seconds);
            if (StepProgress < 1f)
                return false;
            StepProgress = 0f;
            return true;
        }

        private void TickKeributan(float deltaTime, bool fighting)
        {
            if (PoliceCalled)
                return;
            // 0.6.1: once warga shouted, someone always calls the police; they come late,
            // even when the fight is already over (owner: the police must not skip a fight).
            if (Shouted && PoliceEta < 0f)
                PoliceEta = CampaignTuning.Karier.PolisiDatangSeconds;
            if (PoliceEta > 0f)
            {
                PoliceEta -= deltaTime;
                if (PoliceEta <= 0f)
                {
                    CallPolice(KarierPoliceReason.Keributan);
                    return;
                }
            }
            if (CalmLeft > 0f)
            {
                CalmLeft = Math.Max(0f, CalmLeft - deltaTime);
                return;
            }
            if (fighting)
            {
                Keributan = Math.Min(1f, Keributan + deltaTime / CampaignTuning.Karier.KeributanFillSeconds);
                energiCarry += CampaignTuning.Karier.FightEnergiPerSecond * deltaTime;
                if (energiCarry >= 1f)
                {
                    int lost = (int)energiCarry;
                    energiCarry -= lost;
                    AddEnergi(-lost);
                }
                if (!Shouted && Keributan >= CampaignTuning.Karier.TeriakAt)
                {
                    Shouted = true;
                    Say("Warga teriak: \"WOI! ADA YANG BERANTEM!\"  Tetangga berdatangan, HP merekam, ada yang telepon polisi.");
                    Cue(KarierCue.Teriak);
                }
                if (!MeleraiDone && Keributan >= CampaignTuning.Karier.MeleraiAt)
                {
                    MeleraiDone = true;
                    CalmLeft = CampaignTuning.Karier.MeleraiSeconds;
                    Say("Pak RT melerai: \"Sudah, sudah! Malu sama tetangga!\"  Kalau masih ribut, polisi dipanggil.");
                    Cue(KarierCue.Melerai);
                }
                if (Keributan >= 1f)
                    CallPolice(KarierPoliceReason.Keributan);
            }
            else if (Keributan > 0f)
            {
                Keributan = Math.Max(0f, Keributan - deltaTime / CampaignTuning.Karier.KeributanDecaySeconds);
                if (Keributan <= 0f && PoliceEta < 0f)
                    Shouted = MeleraiDone = false;
            }
        }

