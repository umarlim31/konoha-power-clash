        public bool TryLoad(string text)
        {
            if (string.IsNullOrEmpty(text))
                return false;
            string[] parts = text.Split(';');
            // K1 = 0.6.0 save (no missions), K2 = 0.6.1.
            bool v1 = parts.Length == 11 && parts[0] == "K1";
            bool v2 = parts.Length == 14 && parts[0] == "K2";
            bool v3 = parts.Length == 16 && parts[0] == "K3";
            bool v4 = parts.Length == 27 && parts[0] == "K4";
            if (!v1 && !v2 && !v3 && !v4)
                return false;
            var values = new int[parts.Length - 1];
            for (int i = 0; i < values.Length; i++)
                if (!KarierAvatar.Int(parts[i + 1], out values[i]))
                    return false;
            ResetProgress();
            Duit = Math.Max(0, values[0]);
            Energi = Clamp(values[1], 0, CampaignTuning.Karier.EnergiMax);
            Restu = Clamp(values[2], 0, CampaignTuning.Karier.RestuMax);
            CatatanHitam = Clamp(values[3], 0, CampaignTuning.Karier.CatatanMax);
            SapaMask = Math.Max(0, values[4]);
