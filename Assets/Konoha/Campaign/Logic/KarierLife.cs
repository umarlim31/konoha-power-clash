        private static int Clamp(int value, int min, int max) => value < min ? min : value > max ? max : value;

        public static int Round500(float value) => (int)Math.Round(value / 500.0, MidpointRounding.AwayFromZero) * 500;

        // "Rp 1.250.000" (Indonesian thousands separator).
        public static string Rupiah(int value)
        {
            string digits = Math.Abs(value).ToString(CultureInfo.InvariantCulture);
            var builder = new StringBuilder(digits.Length + 6);
            for (int i = 0; i < digits.Length; i++)
            {
                if (i > 0 && (digits.Length - i) % 3 == 0)
                    builder.Append('.');
                builder.Append(digits[i]);
            }
            return (value < 0 ? "-Rp " : "Rp ") + builder;
        }

